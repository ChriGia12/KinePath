// Site language (IT / EN), same scheme as toolpath-check: a dictionary per language, static
// HTML marked with data-i18n*, a toggle button, choice remembered in the browser.
// The geometry core returns messages as { k, p } (key + parameters) instead of Italian text,
// so everything it reports can be shown in the current language — even after switching.

export type Lang = 'it' | 'en';
export interface Msg {
  k: string;
  p?: Record<string, string | number>;
}
export const msg = (k: string, p?: Msg['p']): Msg => ({ k, p });

/** Error carrying a translatable message (thrown by the core, shown by the page). */
export class MsgError extends Error {
  constructor(public m: Msg) {
    super(m.k);
  }
}

/** Parameters outside their admitted values: the computation does not start. */
export class SettingsError extends Error {
  constructor(public errors: Msg[]) {
    super(errors.map((e) => e.k).join(', '));
  }
}

