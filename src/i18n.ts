const DICT: Record<Lang, Record<string, string>> = { it: IT, en: EN };
const KEY = 'kinepath:lang';

let lang: Lang = (() => {
  try {
    return localStorage.getItem(KEY) === 'en' ? 'en' : 'it';
  } catch {
    return 'it';
  }
})();

export const getLang = () => lang;
export const locale = () => (lang === 'en' ? 'en-US' : 'it-IT');

export function setLang(l: Lang) {
  lang = l;
  try {
    localStorage.setItem(KEY, l);
  } catch {
    /* not persisted */
  }
}

/** Translate a key, filling {placeholders}. */
export function t(k: string, p?: Msg['p']): string {
  let s = DICT[lang][k] ?? IT[k] ?? k;
  // A parameter that is itself a key (e.g. a field name) is translated too.
  if (p) for (const [name, v] of Object.entries(p)) s = s.split(`{${name}}`).join(typeof v === 'string' && v in IT ? t(v) : String(v));
  return s;
}

/** Text of a message (plain strings pass through untouched). */
export const tm = (m: Msg | string): string => (typeof m === 'string' ? m : t(m.k, m.p));

/** Apply the language to the static HTML marked with data-i18n, data-i18n-title, data-i18n-aria. */
export function applyStatic(root: ParentNode = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n!)));
  root.querySelectorAll<HTMLElement>('[data-i18n-title]').forEach((el) => (el.title = t(el.dataset.i18nTitle!)));
  root.querySelectorAll<HTMLElement>('[data-i18n-aria]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.i18nAria!)));
}
